#!/bin/bash

# ============================================================
# ClickReady Chart Service - Полный тестовый сценарий
# ============================================================

echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║     ClickReady Chart Service - Полное тестирование API      ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""

# ------------------------------------------------------------------
# 1. HEALTH CHECK
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 1. Health Check"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s http://localhost:8080/api/v1/chart/health
echo ""
echo ""

# ------------------------------------------------------------------
# 2. ПОЛУЧЕНИЕ ТОКЕНА
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🔑 2. Получение JWT токена"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

# Попробовать через /auth/login
TOKEN=$(curl -s -X POST http://localhost:8080/api/v1/auth/login \
  -H "Content-Type: application/json" \
  -d '{"username":"admin"}' \
  | jq -r '.token // empty')

# Если не получилось, попробовать через /test/token
if [ -z "$TOKEN" ] || [ "$TOKEN" = "null" ]; then
    TOKEN=$(curl -s http://localhost:8080/api/v1/test/token)
fi

if [ -z "$TOKEN" ] || [ "$TOKEN" = "null" ]; then
    echo "❌ Не удалось получить токен"
    exit 1
fi

echo "✅ Токен получен: ${TOKEN:0:50}..."
echo ""

# ------------------------------------------------------------------
# 3. ПОЛУЧЕНИЕ ВСЕХ ДАННЫХ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 3. GET /api/v1/chart/data (все данные)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -H "Authorization: Bearer $TOKEN" \
  http://localhost:8080/api/v1/chart/data \
  | jq '.'
echo ""
echo ""

# ------------------------------------------------------------------
# 4. ПОЛУЧЕНИЕ ДАННЫХ ЗА ПЕРИОД
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 4. GET /api/v1/chart/data/range (за период 2026-06-13 - 2026-06-15)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -H "Authorization: Bearer $TOKEN" \
  "http://localhost:8080/api/v1/chart/data/range?startDate=2026-06-13&endDate=2026-06-15" \
  | jq '.'
echo ""
echo ""

# ------------------------------------------------------------------
# 5. СОЗДАНИЕ ДАННЫХ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📝 5. POST /api/v1/chart/data (создание записи за 2026-06-17)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -X POST http://localhost:8080/api/v1/chart/data \
  -H "Content-Type: application/json" \
  -H "Authorization: Bearer $TOKEN" \
  -d '{"date":"2026-06-17","cost":100.0,"cpa":0.5,"roi":200.0,"conversions":150}' \
  | jq '.'
echo ""
echo ""

# ------------------------------------------------------------------
# 6. ПРОВЕРКА СОЗДАННЫХ ДАННЫХ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 6. Проверка созданных данных (2026-06-17)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -H "Authorization: Bearer $TOKEN" \
  "http://localhost:8080/api/v1/chart/data/range?startDate=2026-06-17&endDate=2026-06-17" \
  | jq '.'
echo ""
echo ""

# ------------------------------------------------------------------
# 7. ПАКЕТНОЕ СОЗДАНИЕ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📝 7. POST /api/v1/chart/data/batch (пакетное создание)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -X POST http://localhost:8080/api/v1/chart/data/batch \
  -H "Content-Type: application/json" \
  -H "Authorization: Bearer $TOKEN" \
  -d '[
    {"date":"2026-06-18","cost":120.0,"cpa":0.6,"roi":180.0,"conversions":80},
    {"date":"2026-06-19","cost":130.0,"cpa":0.65,"roi":190.0,"conversions":85}
  ]' \
  | jq '.'
echo ""
echo ""

# ------------------------------------------------------------------
# 8. УДАЛЕНИЕ ДАННЫХ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🗑️ 8. DELETE /api/v1/chart/data/2026-06-18 (удаление записи)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -X DELETE http://localhost:8080/api/v1/chart/data/2026-06-18 \
  -H "Authorization: Bearer $TOKEN" \
  -w "\nHTTP Status: %{http_code}\n"
echo ""

# ------------------------------------------------------------------
# 9. ПРОВЕРКА ПОСЛЕ УДАЛЕНИЯ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 9. Проверка после удаления (2026-06-18 не должно быть)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -H "Authorization: Bearer $TOKEN" \
  "http://localhost:8080/api/v1/chart/data/range?startDate=2026-06-17&endDate=2026-06-19" \
  | jq '.'
echo ""
echo ""

# ------------------------------------------------------------------
# 10. УДАЛЕНИЕ НЕСУЩЕСТВУЮЩЕЙ ЗАПИСИ (404)
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🗑️ 10. DELETE несуществующей записи (должен вернуть 404)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -X DELETE http://localhost:8080/api/v1/chart/data/2026-06-01 \
  -H "Authorization: Bearer $TOKEN" \
  -w "\nHTTP Status: %{http_code}\n"
echo ""

# ------------------------------------------------------------------
# 11. ВСЕГО ЗАПИСЕЙ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 11. Всего записей в БД"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
curl -s -H "Authorization: Bearer $TOKEN" \
  http://localhost:8080/api/v1/chart/data \
  | jq 'length'
echo ""
echo ""

# ------------------------------------------------------------------
# 12. SWAGGER UI
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📚 12. Swagger UI"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Открыть в браузере: http://localhost:8080/swagger-ui.html"
echo ""

# ------------------------------------------------------------------
# 13. КОНЕЦ
# ------------------------------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✅ Все тесты завершены!"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "📋 Полученный токен:"
echo "Bearer $TOKEN"
echo ""
echo "🔗 Полезные ссылки:"
echo "  Swagger UI: http://localhost:8080/swagger-ui.html"
echo "  Grafana:    http://localhost:3000 (admin/admin)"
echo "  Prometheus: http://localhost:9090"
